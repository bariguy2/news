CREATE SCHEMA IF NOT EXISTS news;

CREATE TABLE IF NOT EXISTS news.feeds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    url TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL,
    enabled INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS news.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id BIGINT NOT NULL REFERENCES news.feeds(id),
    url TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    source TEXT NOT NULL,
    category TEXT NOT NULL,
    published_at TEXT,
    fetched_at TEXT NOT NULL,
    raw_excerpt TEXT,
    extracted_text TEXT,
    extraction_ok INTEGER NOT NULL DEFAULT 0,
    summary_facts TEXT,
    summary_impact TEXT,
    summary_status TEXT NOT NULL DEFAULT 'pending', -- unrequested|pending|done|failed
    read_at TEXT
);

ALTER TABLE news.articles ADD COLUMN IF NOT EXISTS read_at TEXT;

CREATE INDEX IF NOT EXISTS idx_articles_published ON news.articles(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_category ON news.articles(category);

CREATE TABLE IF NOT EXISTS news.preferences (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    selected_categories TEXT NOT NULL,
    onboarded INTEGER NOT NULL DEFAULT 0,
    focused_interests TEXT NOT NULL DEFAULT '{}',
    summary_style TEXT NOT NULL DEFAULT '{}'
);

ALTER TABLE news.preferences ADD COLUMN IF NOT EXISTS focused_interests TEXT NOT NULL DEFAULT '{}';
ALTER TABLE news.preferences ADD COLUMN IF NOT EXISTS summary_style TEXT NOT NULL DEFAULT '{}';

ALTER TABLE news.feeds ENABLE ROW LEVEL SECURITY;
ALTER TABLE news.articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE news.preferences ENABLE ROW LEVEL SECURITY;

-- Retained across feed purges/resets for attribution and future feedback.
CREATE TABLE IF NOT EXISTS news.summary_versions (
    id TEXT PRIMARY KEY,
    article_id BIGINT REFERENCES news.articles(id) ON DELETE SET NULL,
    article_url TEXT NOT NULL,
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    prompt_version TEXT NOT NULL,
    input_hash TEXT,
    facts TEXT NOT NULL,
    impact TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_summary_versions_article ON news.summary_versions(article_id);

-- Usage is independent of article retention. Amounts are integer nanodollars.
CREATE TABLE IF NOT EXISTS news.ai_budgets (
    period TEXT NOT NULL,
    scope TEXT NOT NULL,
    used_nano BIGINT NOT NULL DEFAULT 0 CHECK (used_nano >= 0),
    PRIMARY KEY (period, scope)
);
CREATE TABLE IF NOT EXISTS news.ai_attempts (
    id TEXT PRIMARY KEY,
    period TEXT NOT NULL,
    scope TEXT NOT NULL,
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    prompt_version TEXT NOT NULL,
    input_hash TEXT NOT NULL,
    status TEXT NOT NULL,
    reserved_nano BIGINT NOT NULL,
    charged_nano BIGINT NOT NULL,
    input_tokens INTEGER,
    output_tokens INTEGER,
    reasoning_tokens INTEGER,
    estimated INTEGER NOT NULL DEFAULT 1,
    elapsed_ms INTEGER,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ai_attempts_period ON news.ai_attempts(period, scope);

ALTER TABLE news.articles ADD COLUMN IF NOT EXISTS summary_version_id TEXT;
ALTER TABLE news.summary_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE news.ai_budgets ENABLE ROW LEVEL SECURITY;
ALTER TABLE news.ai_attempts ENABLE ROW LEVEL SECURITY;
